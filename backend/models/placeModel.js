import mongoose from 'mongoose';

const placeSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    title: {
      type: String,
      required: true,
    },
    location: {
      name: {
        type: String,
        required: true,
      },
      coordinates: {
        lat: {
          type: Number,
          required: true,
        },
        lng: {
          type: Number,
          required: true,
        },
      },
    },
    streetAddress: {
      type: String,
    },
  },
  { timestamps: true },
);

export default mongoose.model('Place', placeSchema);
